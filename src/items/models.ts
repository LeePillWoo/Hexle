type V3 = [number, number, number];
// 부품: 모양, 색, 위치, 크기, 회전(z → y → x 순서로 적용), 빛나는지
type Part = { g: Geo; c: number; p?: V3; s?: V3 | number; r?: V3; glow?: boolean };
const P = (g: Geo, c: number, p?: V3, s?: V3 | number, r?: V3, glow = false): Part => ({ g, c, p, s, r, glow });
const G = (g: Geo, c: number, p?: V3, s?: V3 | number, r?: V3) => P(g, c, p, s, r, true);

function partGeo(p: Part) {
  const g = GEO[p.g](), s = typeof p.s === 'number' ? [p.s, p.s, p.s] : p.s ?? [1, 1, 1];
  g.scale(s[0], s[1], s[2]);
  if (p.r) { g.rotateZ(p.r[2]); g.rotateY(p.r[1]); g.rotateX(p.r[0]); }
  if (p.p) g.translate(p.p[0], p.p[1], p.p[2]);
  return paint(g, p.c);
}
export function buildParts(parts: Part[]) {
  const g = new THREE.Group();
  const solid = parts.filter(p => !p.glow), glow = parts.filter(p => p.glow);
  if (solid.length) { const m = new THREE.Mesh(merge(...solid.map(partGeo)), vcFlat); m.castShadow = m.receiveShadow = true; g.add(m); }
  if (glow.length) g.add(new THREE.Mesh(merge(...glow.map(partGeo)), glowMat));
  return g;
}

