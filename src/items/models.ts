// 물고기 떼: 작은 물고기 n 마리가 원을 그리며 돈다. update(t) 로 매 프레임 위치 갱신 (그룹 원점 기준)
const tinyFish = merge(paint(new THREE.SphereGeometry(1, 8, 6).scale(0.03, 0.012, 0.008), 0xffffff),
  paint(new THREE.ConeGeometry(1, 1, 3).rotateZ(-Math.PI / 2).scale(0.012, 0.012, 0.003).translate(-0.035, 0, 0), 0xffffff));
const SCHOOL_COLORS = [0x4fc3ff, 0x7fd8ff, 0xffd34f, 0xff9f4f, 0xb0e8ff];
export function makeSchool(n = 22, radius = 0.4) {
  const mesh = new THREE.InstancedMesh(tinyFish, vcFlat, n), m = new THREE.Matrix4(), q = new THREE.Quaternion(), up = new THREE.Vector3(0, 1, 0);
  const base = Math.floor(Math.random() * 5);
  const fish = Array.from({ length: n }, (_, i) => ({ a: i * 2.4, r: radius * (0.55 + 0.45 * Math.random()), y: (Math.random() - 0.5) * 0.18, s: 0.7 + Math.random() * 0.6 }));
  fish.forEach((_, i) => mesh.setColorAt(i, new THREE.Color(SCHOOL_COLORS[(base + (i % 3 === 0 ? 1 : 0)) % 5])));
  const update = (t: number) => {
    fish.forEach((f, i) => {
      const a = t * 0.7 + f.a, x = Math.cos(a) * f.r, z = Math.sin(a) * f.r * 0.7, y = f.y + Math.sin(t * 1.5 + i) * 0.04;
      m.compose(new THREE.Vector3(x, y, z), q.setFromAxisAngle(up, Math.atan2(-0.7 * Math.cos(a), -Math.sin(a))), new THREE.Vector3(f.s, f.s, f.s));
      mesh.setMatrixAt(i, m);
    });
    mesh.instanceMatrix.needsUpdate = true;
  };
  update(0);
  return { mesh, update };
}
